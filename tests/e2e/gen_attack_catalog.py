"""Generates dashboard/src/attacks.ts: every malicious corpus item (plus malware and coverage probes) as a
simulator button. Run from the repo root:  python tests/e2e/gen_attack_catalog.py
Malware entries are harmless stand-ins built in memory (EICAR test file, a script, an executable header and an
APK-shaped archive in a zip). Nothing is executed."""

import base64
import io
import json
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "dashboard" / "src" / "attacks.ts"
EICAR = rb"X5O!P%@AP[4\PZX54(P^)7CC)7}$EICAR-STANDARD-ANTIVIRUS-TEST-FILE!$H+H*"


def zip_b64(files: dict[str, bytes]) -> str:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in files.items():
            z.writestr(name, data)
    return base64.b64encode(buf.getvalue()).decode()


MALWARE = {
    "eicar": ("EICAR test zip (zero-day demo)", zip_b64({"eicar.com": EICAR})),
    "script": ("Script inside a zip (stand-in for AMTSO checks)", zip_b64({"update.ps1": b"Write-Host demo"})),
    "exe": ("Executable inside a zip (stand-in for EMBER)", zip_b64({"invoice.exe": b"MZ" + b"\x00" * 300})),
    "apk": ("APK-shaped zip (stand-in for CICMalDroid)", zip_b64({"AndroidManifest.xml": b"<manifest/>", "classes.dex": b"dex\x00" * 64})),
    "deps": ("Outdated dependency file (A03 probe)", zip_b64({"requirements.txt": b"log4j==2.14.1\n"})),
}


def main() -> None:
    owasp = {k: [] for k in ["A01", "A02", "A03", "A04", "A05", "A06", "A07", "A08", "A09", "A10"]}
    for line in (ROOT / "tests" / "corpus" / "corpus.jsonl").read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        r = json.loads(line)
        if r["label"] == "benign":
            continue
        a = {"id": r["id"], "label": f'{r["id"]} {r.get("notes", "")[:60]}', "method": r["method"],
             "path": r["path"] + (("?" + r["query"]) if r.get("query") else "")}
        if r.get("body") is not None:
            a["body"] = json.dumps(r["body"]) if isinstance(r["body"], (dict, list)) else str(r["body"])
        owasp[r["owasp"]].append(a)
    # coverage probes for categories with no corpus item yet: no rule detects them today
    owasp["A03"].append({"id": "probe-a03", "label": "outdated dependency upload", "method": "POST",
                         "path": "/api/statements/upload", "zip": "deps"})
    owasp["A04"].append({"id": "probe-a04", "label": "login over plain HTTP", "method": "POST", "path": "/api/login",
                         "body": "email=customer1%40example.test&password=password123"})
    owasp["A08"].append({"id": "probe-a08", "label": "unsigned session token", "method": "GET",
                         "path": "/api/accounts/1?session=eyJhbGciOiJub25lIn0.e30."})
    owasp["A09"].append({"id": "probe-a09", "label": "memo with no audit trail", "method": "POST",
                         "path": "/api/transactions/45/memo", "body": '{"memo":"audit: nothing logged"}'})

    lines = [
        "// GENERATED by tests/e2e/gen_attack_catalog.py. Do not edit by hand; regenerate.",
        "// Every item is a labelled corpus item, a malware stand-in or a coverage probe, sent as-is to the gateway.",
        "",
        "export type Attack = { id: string; label: string; method: \"GET\" | \"POST\"; path: string; body?: string; zip?: string };",
        "",
        "export const MALWARE: Record<string, { label: string; zipB64: string }> = {",
    ]
    for key, (label, b64) in MALWARE.items():
        lines.append(f"  {json.dumps(key)}: {{ label: {json.dumps(label)}, zipB64: {json.dumps(b64)} }},")
    lines += ["};", "", "export const OWASP_ATTACKS: Record<string, Attack[]> = {"]
    for key, items in owasp.items():
        lines.append(f"  {json.dumps(key)}: [")
        for a in items:
            parts = [f"{k}: {json.dumps(v)}" for k, v in a.items()]
            lines.append("    { " + ", ".join(parts) + " },")
        lines.append("  ],")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print({k: len(v) for k, v in owasp.items()}, "->", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
